"""Published statements of the chart-asset write guarantee (compact-chart-assets 6.1).

The ownership contract states, under "What Regeneration Replaces and
Preserves", that a workout chart asset whose regenerated bytes equal the file at
its path is left untouched and that a changed one is replaced without partial
content (Req 9.1); its version advances by one with a statement of what changed
(Req 9.2). Each pin is the sentence a reader relies on.
"""

from __future__ import annotations

import inspect
from pathlib import Path

from fitdocs import contract
from fitdocs.contract import CONTRACT_VERSION

ROOT = Path(__file__).resolve().parents[1]
DOC = ROOT / "docs/ownership-contract.md"


def _flat(text: str) -> str:
    return " ".join(text.split())


def _section(text: str, heading: str) -> str:
    body = text.split(f"\n## {heading}\n", 1)[1]
    return _flat(body.split("\n## ", 1)[0])


def test_contract_version_is_seventeen() -> None:
    assert CONTRACT_VERSION == "17"
    head = _flat(DOC.read_text(encoding="utf-8")).split(" ## ", 1)[0]
    assert f"**Contract version:** `{CONTRACT_VERSION}`" in head


def test_version_head_states_the_asset_write_guarantee() -> None:
    head = _flat(DOC.read_text(encoding="utf-8")).split(" ## ", 1)[0]
    for phrase in (
        "whose regenerated bytes equal the file already at its path is "
        "left untouched, content and modification time",
        "its path holds either the previous complete file or the new complete "
        "file, never a partial one",
        "Nothing is needed for existing documents",
    ):
        assert phrase in head, phrase


def test_replaces_and_preserves_states_the_asset_write_guarantee() -> None:
    section = _section(
        DOC.read_text(encoding="utf-8"), "What Regeneration Replaces and Preserves"
    )
    for phrase in (
        "Chart assets are replaced only when their content changes.",
        "A chart asset under `workouts/assets/` whose regenerated bytes are "
        "identical to the file already at its path is left untouched, content "
        "and modification time",
        "A changed or new asset is written to a hidden temporary file beside "
        "it and swapped into place, so its path holds either the previous "
        "complete file or the new complete file, never a partial one",
        "A write that fails with an error removes its temporary file; a run "
        "killed mid-write can leave one behind, a hidden `.<name>.<random>.tmp` "
        "file that fitdocs does not read and that is safe to delete.",
    ):
        assert phrase in section, phrase
    # The sentence that said every asset is replaced is qualified, not left standing.
    assert "and every chart asset. It carries" not in section


def test_contract_version_history_records_the_asset_guarantee() -> None:
    history = _flat(inspect.getsource(contract))
    assert "Raised from ``16`` to ``17`` by compact-chart-assets" in history
    assert (
        "a workout chart asset whose regenerated bytes equal the file at its "
        "path is left untouched, content and modification time"
    ) in history
